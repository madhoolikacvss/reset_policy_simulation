#!/usr/bin/env python3
"""
FROZEN evaluation harness. Do not edit this file (or anything in data/).

Usage:
    python benchmark.py                      # evaluate params.yaml on data/train
    python benchmark.py --split val          # held-out episodes (use sparingly, end of work)
    python benchmark.py --params other.yaml --per-episode

Metric (all errors are mean Euclidean distance in NORMALIZED [x, y] units, per row):
    one_step : sim started from the real start-of-step state at EVERY row (resync_horizon=1),
               compared with the real end-of-step state.
    rollout  : sim resynced to the real start state every ROLLOUT_H=20 rows, free-running between.
    long     : sim resynced every LONG_H=100 rows (episodes are ~400 steps), so errors that
               accumulate over a long run are scored. A model that barely moves the cube cannot
               win this term when the real cube drifts.
    open     : sim never resynced after row 0 (diagnostic only, not in the score).
    off      : fraction of long-rollout steps where the cube hit the board edge (should be ~0).

    score = (one_step + rollout + long) / 3 + 0.1 * off          (mean over episodes, LOWER is better)

Baselines reported next to every score:
    stationary : the cube stays at the last resynced state (same formula for every horizon, off = 0).
    skill      : 1 - score / stationary_score        (> 0 means better than doing nothing)
    linear_ref : one-step error of a linear map executed_actions -> displacement, fitted on
                 data/train. It is a diagnostic ceiling for one-step error, not a sim.
The harness overrides resync_horizon itself; the value in params.yaml is ignored here.
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
import time
from dataclasses import replace
from pathlib import Path

import numpy as np

import sim_core as sc
from params import Params, load_params

ROLLOUT_H = 20
LONG_H = 100
W_ONE = W_ROLL = W_LONG = 1.0 / 3.0
W_OFF = 0.1


def _stationary(ep: sc.Episode, horizon: int) -> np.ndarray:
    n = len(ep.real_norm)
    idx = np.zeros(n, dtype=int) if horizon == 0 else (np.arange(n) // horizon) * horizon
    return ep.start_norm[idx]


def _err(pred: np.ndarray, real: np.ndarray) -> float:
    pred = np.nan_to_num(pred, nan=1.0, posinf=1.0, neginf=-1.0)
    return float(np.linalg.norm(pred - real, axis=1).mean())


def load_split(data_dir: Path, split: str) -> list[sc.Episode]:
    files = sorted((data_dir / split).glob("*.csv"))
    return [sc.load_episode(f) for f in files]


def fit_linear_ref(train: list[sc.Episode]) -> np.ndarray | None:
    if not train:
        return None
    X = np.vstack([np.c_[e.executed, np.ones(len(e.executed))] for e in train])
    Y = np.vstack([e.real_norm - e.start_norm for e in train])
    return np.linalg.lstsq(X, Y, rcond=None)[0]


def evaluate(p: Params, episodes: list[sc.Episode], linear_w: np.ndarray | None = None,
             include_open: bool = True) -> dict:
    """Importable by an optimizer: returns aggregate and per-episode metrics.
    include_open=False skips the diagnostic open-loop run (about 1/3 faster); the score is unchanged."""
    rows = []
    for ep in episodes:
        one = sc.simulate_episode(ep, replace(p, resync_horizon=1))
        roll = sc.simulate_episode(ep, replace(p, resync_horizon=ROLLOUT_H))
        lng = sc.simulate_episode(ep, replace(p, resync_horizon=LONG_H))
        opn = sc.simulate_episode(ep, replace(p, resync_horizon=0)) if include_open else None
        r = {
            "episode": ep.name,
            "rows": len(ep.real_norm),
            "one_step": _err(one.pred_norm, ep.real_norm),
            "rollout": _err(roll.pred_norm, ep.real_norm),
            "long": _err(lng.pred_norm, ep.real_norm),
            "open": _err(opn.pred_norm, ep.real_norm) if include_open else float("nan"),
            "off": lng.off_board_rows / len(ep.real_norm),
            "stat_one": _err(_stationary(ep, 1), ep.real_norm),
            "stat_roll": _err(_stationary(ep, ROLLOUT_H), ep.real_norm),
            "stat_long": _err(_stationary(ep, LONG_H), ep.real_norm),
            "stat_open": _err(_stationary(ep, 0), ep.real_norm),
        }
        if linear_w is not None:
            lin = ep.start_norm + np.c_[ep.executed, np.ones(len(ep.executed))] @ linear_w
            r["linear_ref"] = _err(lin, ep.real_norm)
        rows.append(r)

    m = lambda k: float(np.mean([r[k] for r in rows]))
    score = W_ONE * m("one_step") + W_ROLL * m("rollout") + W_LONG * m("long") + W_OFF * m("off")
    stat_score = W_ONE * m("stat_one") + W_ROLL * m("stat_roll") + W_LONG * m("stat_long")
    out = {
        "score": score,
        "stationary_score": stat_score,
        "skill": 1.0 - score / stat_score if stat_score > 0 else float("nan"),
        "one_step": m("one_step"), "stat_one": m("stat_one"),
        "rollout": m("rollout"), "stat_roll": m("stat_roll"),
        "long": m("long"), "stat_long": m("stat_long"),
        "open": m("open"), "stat_open": m("stat_open"),
        "off": m("off"),
        "episodes": rows,
    }
    if linear_w is not None:
        out["linear_ref"] = m("linear_ref")
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--params", default="params.yaml")
    ap.add_argument("--data-dir", default="data")
    ap.add_argument("--split", choices=["train", "val", "all"], default="train")
    ap.add_argument("--results", default="results.csv", help="append a row per run here")
    ap.add_argument("--no-log", action="store_true")
    ap.add_argument("--per-episode", action="store_true")
    args = ap.parse_args()

    data_dir = Path(args.data_dir)
    try:
        p = load_params(args.params)
    except Exception as e:  # invalid or out-of-bounds params
        print(f"INVALID PARAMS: {e}", file=sys.stderr)
        return 1

    splits = ["train", "val"] if args.split == "all" else [args.split]
    episodes = [e for s in splits for e in load_split(data_dir, s)]
    if not episodes:
        print(f"No episodes found under {data_dir}/{args.split}", file=sys.stderr)
        return 2
    if args.split != "train":
        print("NOTE: held-out data. Do not tune against it.", file=sys.stderr)

    t0 = time.time()
    res = evaluate(p, episodes, fit_linear_ref(load_split(data_dir, "train")))
    dt = time.time() - t0

    if args.per_episode:
        hdr = (f"{'episode':28s} {'one':>7s} {'(stat)':>7s} {'roll':>7s} {'(stat)':>7s} "
               f"{'long':>7s} {'(stat)':>7s} {'open':>7s} {'off':>5s}")
        print(hdr)
        for r in res["episodes"]:
            print(f"{r['episode']:28s} {r['one_step']:7.4f} {r['stat_one']:7.4f} "
                  f"{r['rollout']:7.4f} {r['stat_roll']:7.4f} {r['long']:7.4f} {r['stat_long']:7.4f} "
                  f"{r['open']:7.4f} {r['off']:5.2f}")
    lin = f"  linear_ref(one_step)={res['linear_ref']:.4f}" if "linear_ref" in res else ""
    print(f"split={args.split} episodes={len(episodes)} time={dt:.1f}s")
    print(f"one_step={res['one_step']:.4f} (stationary {res['stat_one']:.4f}){lin}")
    print(f"rollout{ROLLOUT_H}={res['rollout']:.4f} (stationary {res['stat_roll']:.4f})")
    print(f"long{LONG_H}={res['long']:.4f} (stationary {res['stat_long']:.4f})")
    print(f"open_loop={res['open']:.4f} (stationary {res['stat_open']:.4f})  off_board_frac={res['off']:.3f}")
    print(f"stationary_score={res['stationary_score']:.5f}  skill={res['skill']:+.3f}")
    print(f"SCORE: {res['score']:.5f}")

    if not args.no_log:
        path = Path(args.results)
        new = not path.exists()
        with open(path, "a", newline="") as f:
            w = csv.writer(f)
            if new:
                w.writerow(["time", "split", "score", "skill", "one_step", "rollout", "long", "open", "off", "params"])
            w.writerow([time.strftime("%Y-%m-%d %H:%M:%S"), args.split, f"{res['score']:.6f}",
                        f"{res['skill']:.4f}", f"{res['one_step']:.6f}", f"{res['rollout']:.6f}",
                        f"{res['long']:.6f}", f"{res['open']:.6f}", f"{res['off']:.4f}", json.dumps(p.to_dict())])
    return 0


if __name__ == "__main__":
    sys.exit(main())